// Syncthing ignore block for git repos under the coding root. Code moves through GitHub only,
// so Syncthing must never sync a repo folder (working files would show up as the other Mac's
// uncommitted edits). Pure functions plus a small walker; no dependencies.
import fs from 'node:fs';
import path from 'node:path';

export const BEGIN = '// BEGIN mithtech-kit repos (generated by kit/scripts/stignore.mjs; do not edit inside)';
export const END = '// END mithtech-kit repos';
const SKIP = new Set(['node_modules', '.venv', 'venv', 'env', 'target', '.next', '.turbo', '.dart_tool', '.gradle', 'Pods',
  '__pycache__', '.stversions', '.stfolder', '.Trash', '.Trashes', '.Spotlight-V100', '.cache']);

// Every folder under root that holds a .git (dir or file). Stops at a repo root: a nested repo
// is covered by its parent's ignore line. Returns paths relative to root with forward slashes.
export function findRepos(root, { maxDepth = 8 } = {}) {
  const found = [];
  const walk = (dir, depth) => {
    let ents;
    try { ents = fs.readdirSync(dir, { withFileTypes: true }); } catch { return; }
    if (dir !== root && ents.some((e) => e.name === '.git')) { found.push(path.relative(root, dir).split(path.sep).join('/')); return; }
    if (depth >= maxDepth) return;
    for (const e of ents) {
      if (!e.isDirectory() || e.isSymbolicLink() || SKIP.has(e.name) || e.name === '.git') continue;
      walk(path.join(dir, e.name), depth + 1);
    }
  };
  walk(root, 0);
  return found.sort();
}

// Lines for the block: one anchored pattern per repo. Characters Syncthing treats as glob syntax are escaped.
export function blockLines(repos) {
  return repos.map((r) => '/' + r.replace(/([*?[\]{}\\])/g, '\\$1'));
}

// Replace (or append) the marked block; keep every user line outside it.
export function renderIgnore(text, repos) {
  const block = [BEGIN, ...blockLines(repos), END].join('\n');
  const s = text.indexOf(BEGIN), e = text.indexOf(END);
  if (s >= 0 && e > s) return text.slice(0, s) + block + text.slice(e + END.length);
  return (text.replace(/\s*$/, '') + (text.trim() ? '\n\n' : '') + block + '\n');
}

export function currentBlock(text) {
  const s = text.indexOf(BEGIN), e = text.indexOf(END);
  if (s < 0 || e < s) return null;
  return text.slice(s + BEGIN.length, e).split('\n').map((l) => l.trim()).filter(Boolean);
}

// Repos that no ignore line covers. Understands anchored and unanchored plain paths and
// simple * globs; good enough to warn, not a full Syncthing matcher.
export function unignored(text, repos) {
  const pats = text.split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('//') && !l.startsWith('#') && !l.startsWith('!'))
    .map((l) => l.replace(/^\(\?[di]+\)/, ''));
  const toRe = (p) => {
    const anchored = p.startsWith('/');
    const body = p.replace(/^\//, '').replace(/\\([*?[\]{}\\])/g, '\u0000$1').replace(/[.+^$()|]/g, '\\$&')
      .replace(/\*\*/g, '\u0001').replace(/\*/g, '[^/]*').replace(/\u0001/g, '.*').replace(/\?/g, '[^/]')
      .replace(/\u0000(.)/g, (m, c) => '\\' + c);
    return new RegExp((anchored ? '^' : '(^|/)') + body + '(/|$)');
  };
  const res = pats.map(toRe);
  return repos.filter((r) => !res.some((re) => re.test(r)));
}

// Regenerate the block in <root>/.stglobalignore. Returns { changed, repos, file }.
export function generate(root, { dryRun = false } = {}) {
  const file = path.join(root, '.stglobalignore');
  const before = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  const repos = findRepos(root);
  const after = renderIgnore(before, repos);
  const changed = after !== before;
  if (changed && !dryRun) fs.writeFileSync(file, after);
  return { changed, repos, file, text: after };
}
